#!/usr/bin/env bash
# Grant the deploy user passwordless control of the pe-service systemd units.
#
# Run ON the VPS as root (one time; idempotent):   sudo bash scripts/vps_grant_pe_service_sudo.sh [user]
# From the dev box (one line):
#   scp -i ~/.ssh/id_personal scripts/vps_grant_pe_service_sudo.sh sean@82.22.32.225:/tmp/grant.sh \
#     && ssh -t -i ~/.ssh/id_personal sean@82.22.32.225 'sudo bash /tmp/grant.sh && rm -f /tmp/grant.sh'
#
# Scope (docs/35): exact `systemctl` verbs on the named units plus `daemon-reload`. sudo matches
# the full argument list, so nothing else is granted — no shell, no `systemctl edit` (opens an
# editor as root), no other units.
#
# Safety preconditions, checked per unit before anything is written (a restart grant is only
# harmless when restarting cannot run the deploy user's code with more privilege than it has):
#   - the unit is loaded with an explicit non-root `User=`;
#   - its unit file and every drop-in are root-owned;
#   - if the unit runs as a DIFFERENT account than the deploy user, its ExecStart executable
#     must not be writable by the deploy user (otherwise a restart would run deploy-user code
#     as that account). A unit that runs as the deploy user itself gains nothing new.
# The drop-in is rendered to a temp file, checked with `visudo -cf`, installed atomically, and the
# FULL sudoers configuration is re-validated; on any failure the previous file (or absence) is
# restored, so a broken drop-in is never left behind.
set -euo pipefail

user="${1:-sean}"
systemctl_bin="$(command -v systemctl)"
units=(pe-service pe-service-live-canary)
verbs=(start stop restart reload reload-or-restart try-restart kill reset-failed enable disable)
file=/etc/sudoers.d/pe-service-control

if [ "$(id -u)" -ne 0 ]; then
  echo "run as root: sudo bash $0 [user]" >&2
  exit 1
fi
id -u "$user" >/dev/null

fail() { echo "refusing to install: $*" >&2; exit 1; }

for unit in "${units[@]}"; do
  if [ "$(systemctl show "$unit" -p LoadState --value)" != "loaded" ]; then
    fail "$unit is not a loaded unit"
  fi
  unit_user="$(systemctl show "$unit" -p User --value)"
  [ -n "$unit_user" ] && [ "$unit_user" != "root" ] || fail "$unit has no non-root User="
  fragment="$(systemctl show "$unit" -p FragmentPath --value)"
  for f in "$fragment" $(systemctl show "$unit" -p DropInPaths --value); do
    [ "$(stat -c %U "$f")" = "root" ] || fail "$f is not root-owned"
  done
  if [ "$unit_user" != "$user" ]; then
    exe="$(systemctl show "$unit" -p ExecStart --value | sed -n 's/.*path=\([^ ;]*\).*/\1/p' | head -n1)"
    [ -n "$exe" ] || fail "$unit has no ExecStart path"
    if sudo -u "$user" test -w "$exe"; then
      fail "$unit runs as $unit_user but its executable $exe is writable by $user"
    fi
  fi
  echo "ok: $unit runs as $unit_user; unit files root-owned"
done

tmp="$(mktemp)"
backup="$(mktemp)"
had_prior=0
cleanup() { rm -f "$tmp" "$backup"; }
trap cleanup EXIT
{
  echo "# Generated by scripts/vps_grant_pe_service_sudo.sh: passwordless control of the pe-service units only."
  printf 'Cmnd_Alias PE_SERVICE_CTL = %s daemon-reload' "$systemctl_bin"
  for unit in "${units[@]}"; do
    for verb in "${verbs[@]}"; do
      printf ', \\\n    %s %s %s' "$systemctl_bin" "$verb" "$unit"
    done
  done
  echo
  echo "$user ALL=(root) NOPASSWD: PE_SERVICE_CTL"
} > "$tmp"

visudo -cf "$tmp"
if [ -f "$file" ]; then
  cp -p "$file" "$backup"
  had_prior=1
fi
install -o root -g root -m 0440 "$tmp" "$file.new"
mv -f "$file.new" "$file"
if ! visudo -c >/dev/null; then
  if [ "$had_prior" -eq 1 ]; then
    install -o root -g root -m 0440 "$backup" "$file"
  else
    rm -f "$file"
  fi
  fail "full sudoers validation failed after install; previous state restored"
fi

echo "installed $file:"
cat "$file"
echo
echo "effective for $user:"
sudo -l -U "$user" | sed -n '/may run/,$p'
