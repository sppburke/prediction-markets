//! Operator-level scenario tests for the infra-wallet pre-filter probe (issue #197).
//!
//! Covers the cold-start probe wired into `PolymarketBulkFetcher::fetch_all`
//! and the retroactive `classify_infra_retroactive` SQL sweep.
//!
//! PASS criteria are stated inline above each test.

#![cfg(feature = "scenario")]
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::collections::HashMap;

use pe_bootstrap::cache::WalletCache;
use pe_bootstrap::pile::SRC_WALLET_SET_JSON;
use pe_bootstrap::polymarket::PolymarketBulkFetcher;
use pe_core_types::WalletAddress;
use pe_source_polymarket_public::{FixtureFetcher, PolymarketEndpoint};
use tempfile::TempDir;

const BASE_URL: &str = "https://data-api.polymarket.com";

fn wallet(byte: u8) -> WalletAddress {
    WalletAddress::from_hex(&format!("0x{:040x}", byte)).unwrap()
}

fn open_cache_with_wallet(dir: &TempDir, w: WalletAddress) -> WalletCache {
    let path = dir.path().join("cache.db");
    let mut cache = WalletCache::open(&path).unwrap();
    cache
        .upsert_wallets_bulk(&[(
            w.to_string(),
            SRC_WALLET_SET_JSON,
            false,
            None,
            None,
            None,
            0,
        )])
        .unwrap();
    cache
}

fn cold_url(w: WalletAddress) -> String {
    PolymarketEndpoint::UserTradeActivityPage {
        user: w.to_string(),
        end: 2_000_000_000,
        start: Some(1),
        offset: 0,
    }
    .url(BASE_URL)
}

fn next_backward_url(w: WalletAddress, end_ts: i64) -> String {
    PolymarketEndpoint::UserTradeActivityPage {
        user: w.to_string(),
        end: end_ts,
        start: Some(1),
        offset: 0,
    }
    .url(BASE_URL)
}

fn serve_second(
    pages: &mut HashMap<String, Vec<u8>>,
    w: WalletAddress,
    second: i64,
    page: Vec<u8>,
) {
    let rows: Vec<serde_json::Value> = serde_json::from_slice(&page).unwrap();
    let rows: Vec<_> = rows
        .into_iter()
        .filter(|r| r["timestamp"].as_i64() == Some(second))
        .collect();
    pages.insert(
        PolymarketEndpoint::UserTradeActivityPage {
            user: w.to_string(),
            end: second,
            start: Some(second),
            offset: 0,
        }
        .url(BASE_URL),
        serde_json::to_vec(&rows).unwrap(),
    );
}

/// Build a page JSON with `n` synthetic trades, with timestamps generated by
/// `ts_for(i)`. Trade ID prefixed with `id_prefix` so multiple pages can be
/// distinguished.
fn trades_page(n: usize, ts_for: impl Fn(usize) -> i64, id_prefix: &str) -> Vec<u8> {
    let mut s = String::from("[");
    for i in 0..n {
        if i > 0 {
            s.push(',');
        }
        let tid = format!("0x{id_prefix}{i:062x}");
        let mid = format!("0x{:064x}", i + 1);
        s.push_str(&format!(
            r#"{{"transactionHash":"{tid}","conditionId":"{mid}","outcomeIndex":0,"side":"BUY","price":"0.5","size":"1","timestamp":{ts}}}"#,
            ts = ts_for(i)
        ));
    }
    s.push(']');
    s.into_bytes()
}

fn empty_page() -> Vec<u8> {
    b"[]".to_vec()
}

// ── Scenario 1: probe fires on dense full page ────────────────────────────────
//
// PASS: 500 trades within 60 seconds → wallet flagged is_infra=1, NO trades
//       inserted into cache, wallet not in FetchOutcome::failed.
// FAIL: trades inserted, or wallet missing from is_infra flagging.

#[tokio::test]
async fn probe_fires_on_dense_full_page() {
    let dir = TempDir::new().unwrap();
    let w = wallet(0xAA);
    let mut cache = open_cache_with_wallet(&dir, w);

    // 500 trades all within the first 60 seconds → dense → infra.
    let mut pages: HashMap<String, Vec<u8>> = HashMap::new();
    pages.insert(
        cold_url(w),
        trades_page(500, |i| 1_700_000_000 + (i as i64 % 60), "aa"),
    );

    let fetcher = PolymarketBulkFetcher::new(BASE_URL.to_owned(), FixtureFetcher::new(pages))
        .with_clock_for_test(|| 2_000_000_120)
        .with_concurrency(1);
    let outcome = fetcher.fetch_all(&[w], &mut cache).await.unwrap();

    assert_eq!(
        outcome.failed.len(),
        0,
        "probe-flagged wallet must not be in failed set"
    );
    assert!(
        cache.conn_for_test_is_infra(&w.to_string()),
        "wallet must be flagged is_infra=1 after probe fires"
    );
    assert!(
        cache.trades_for(&w.to_string()).is_empty(),
        "probe page must be discarded — no trades in cache"
    );
}

// ── Scenario 2: probe passes on sparse full page ──────────────────────────────
//
// PASS: 500 trades spanning ~48 hours → not infra, trades inserted, is_infra=0.
// FAIL: wallet flagged infra, or trades dropped.

#[tokio::test]
async fn probe_passes_on_sparse_full_page() {
    let dir = TempDir::new().unwrap();
    let w = wallet(0xBB);
    let mut cache = open_cache_with_wallet(&dir, w);

    // 500 trades over 48h (~346s apart) → 172_500s span >> 3600s → not infra.
    let mut pages: HashMap<String, Vec<u8>> = HashMap::new();
    let base_ts: i64 = 1_700_000_000;
    pages.insert(
        cold_url(w),
        trades_page(500, |i| base_ts + (i as i64) * 346, "bb"),
    );
    // Pagination terminator: the next backward page (cursor = oldest_ts - 1).
    // Oldest in our page is base_ts (i=0); so the cursor is base_ts - 1.
    serve_second(
        &mut pages,
        w,
        base_ts,
        trades_page(500, |i| base_ts + (i as i64) * 346, "bb"),
    );
    pages.insert(next_backward_url(w, base_ts - 1), empty_page());

    let fetcher = PolymarketBulkFetcher::new(BASE_URL.to_owned(), FixtureFetcher::new(pages))
        .with_clock_for_test(|| 2_000_000_120)
        .with_concurrency(1);
    let outcome = fetcher.fetch_all(&[w], &mut cache).await.unwrap();

    assert_eq!(outcome.failed.len(), 0);
    assert!(
        !cache.conn_for_test_is_infra(&w.to_string()),
        "sparse wallet must NOT be flagged infra"
    );
    let n_trades = cache.trades_for(&w.to_string()).len();
    assert_eq!(n_trades, 500, "all 500 trades must be inserted");
}

// ── Scenario 3: probe skipped on partial page ─────────────────────────────────
//
// PASS: page with raw_count < 500 → no probe → trades inserted, is_infra=0.
// FAIL: probe fires (would be a false positive) or trades dropped.

#[tokio::test]
